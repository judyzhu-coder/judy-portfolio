function openProject(projectId) {
  const project = projects[projectId];
  if (!project) return;
  dialogMeta.textContent = project.meta;
  dialogTitle.textContent = project.title;
  dialogSummary.textContent = project.summary;
  dialogFacts.replaceChildren(...project.facts.map(([label, value]) => {
    const wrapper = document.createElement("div");
    const term = document.createElement("dt");
    const detail = document.createElement("dd");
    term.textContent = label;
    detail.textContent = value;
    wrapper.append(term, detail);
    return wrapper;
  }));
  dialogBody.replaceChildren(...project.body.map((copy) => {
    const paragraph = document.createElement("p");
    paragraph.textContent = copy;
    return paragraph;
  }));
  dialogGallery.replaceChildren(...project.images.map(([src, alt]) => {
    const image = document.createElement("img");
    image.src = src;
    image.alt = alt;
    image.loading = "lazy";
    image.decoding = "async";
    attachMediaFallback(image);
    return image;
  }));
  dialogGallery.hidden = project.images.length === 0;
  dialogLinks.replaceChildren(...project.links.map(([label, href]) => {
    const link = document.createElement("a");
    link.className = "primary-action";
    link.href = href;
    link.target = "_blank";
    link.rel = "noreferrer";
    link.textContent = `${label} ↗`;
    return link;
  }));
  document.body.classList.add("dialog-open");
  dialog.showModal();
}

document.querySelectorAll("[data-open-project]").forEach((button) => button.addEventListener("click", () => openProject(button.dataset.openProject)));
