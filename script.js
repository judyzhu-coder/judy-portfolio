const root = document.documentElement;
const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
const mediaCdnPrefix = "https://cdn.jsdelivr.net/gh/judyzhu-coder/judy-portfolio@main/";

function attachMediaFallback(element) {
  const remoteSource = element.getAttribute("src");
  if (!remoteSource?.startsWith(mediaCdnPrefix)) return;
  const localSource = remoteSource.slice(mediaCdnPrefix.length);
  element.addEventListener("error", () => {
    if (element.getAttribute("src") === localSource) return;
    element.setAttribute("src", localSource);
    if (element.tagName === "SOURCE") element.parentElement?.load();
  }, { once: true });
}

document.querySelectorAll("img, video source").forEach(attachMediaFallback);

