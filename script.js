const revealElements = [...document.querySelectorAll(".reveal")];
if (!reduceMotion && "IntersectionObserver" in window) {
  root.classList.add("motion-ready");
  const revealObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("is-visible");
      revealObserver.unobserve(entry.target);
    });
  }, { threshold: 0.08 });
  revealElements.forEach((element) => revealObserver.observe(element));
} else {
  revealElements.forEach((element) => element.classList.add("is-visible"));
}

if (!reduceMotion && window.matchMedia("(hover: hover) and (pointer: fine)").matches) {
  document.querySelectorAll("[data-parallax]").forEach((element) => {
    element.addEventListener("pointermove", (event) => {
      const bounds = element.getBoundingClientRect();
      const x = (event.clientX - bounds.left) / bounds.width - 0.5;
      const y = (event.clientY - bounds.top) / bounds.height - 0.5;
      element.style.setProperty("--rx", `${(-y * 2.2).toFixed(2)}deg`);
      element.style.setProperty("--ry", `${(x * 3).toFixed(2)}deg`);
    });
    element.addEventListener("pointerleave", () => {
      element.style.setProperty("--rx", "0deg");
      element.style.setProperty("--ry", "0deg");
    });
  });
}

document.querySelectorAll("[data-carousel]").forEach((carousel) => {
  const slides = [...carousel.querySelectorAll(".carousel-slide")];
  const thumbs = [...carousel.querySelectorAll("[data-carousel-to]")];
  let active = 0;
  let timer;
  const show = (index) => {
    active = (index + slides.length) % slides.length;
    slides.forEach((slide, slideIndex) => {
      const selected = slideIndex === active;
      slide.classList.toggle("is-active", selected);
      slide.setAttribute("aria-hidden", String(!selected));
    });
    thumbs.forEach((thumb, thumbIndex) => {
      const selected = thumbIndex === active;
      thumb.classList.toggle("is-active", selected);
      thumb.setAttribute("aria-pressed", String(selected));
    });
  };
  const stop = () => window.clearInterval(timer);
  const start = () => {
    if (reduceMotion) return;
    stop();
    timer = window.setInterval(() => show(active + 1), 5200);
  };
  carousel.querySelector("[data-carousel-prev]").addEventListener("click", () => { show(active - 1); start(); });
  carousel.querySelector("[data-carousel-next]").addEventListener("click", () => { show(active + 1); start(); });
  thumbs.forEach((thumb) => thumb.addEventListener("click", () => { show(Number(thumb.dataset.carouselTo)); start(); }));
  carousel.addEventListener("mouseenter", stop);
  carousel.addEventListener("mouseleave", start);
  carousel.addEventListener("focusin", stop);
  carousel.addEventListener("focusout", start);
  show(0);
  start();
});

